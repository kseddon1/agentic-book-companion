#!/usr/bin/env python3
"""
pipeline/researchers/research.py — Chapter 1 Lab: research (retrieve + synthesize)

PRODUCTION NOTE: freemarketresearcher.com's real researchers live in
RagSystem/researchers/{base,finance,tech,ag,...}.py. Each run makes
several chained LLM calls (query transformation -> retrieval -> reranking
-> synthesis), per RagSystem/core/{query_transformation,reranking}.py,
against a real Qdrant collection. That chain of model calls IS the
agentic runtime (GOAL.md Section 0.2.1) -- Hermes and MCP are the
interactive layer used to build and inspect it, not the runtime path.

This module is the Chapter 1 teaching stand-in: one retrieval step
(cosine similarity over the JSON pseudo-vector-store from crawl.py) plus
one synthesis call. No query transformation, no reranking.

Model routing (see pipeline/config.example.yaml `model:` section):
  1. HOSTED (recommended -- zero GPU, zero local setup): set
     OPENROUTER_API_KEY (or OPENAI_API_KEY) in the environment. Calls an
     OpenAI-compatible /chat/completions endpoint over HTTPS with the
     Python stdlib (urllib) -- no SDK install required.
  2. LOCAL (optional): if no hosted key is set, checks whether an Ollama
     server is already running at http://localhost:11434 and uses it if
     so. Never required; no GPU check is performed beyond "is the port
     open", matching GOAL.md's "local GPU is optional" rule.
  3. MOCK / DRY-RUN (default on a bare checkout with no key and no
     Ollama running): prints exactly what request WOULD have been sent,
     and writes a clearly labeled mock report instead of crashing. This
     is what makes the Lab runnable at zero cost with no setup.
"""
import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Optional

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

from pipeline.config import load_config  # noqa: E402
from pipeline.crawler.crawl import cosine, hash_embedding  # noqa: E402
from pipeline.researchers.query_transform import expand_query  # noqa: E402
from pipeline.researchers.rerank import rerank  # noqa: E402


def retrieve(query: str, store_path, top_k: int = 5, min_score: float = 0.0):
    store_path = Path(store_path)
    if not store_path.exists():
        return []
    data = json.loads(store_path.read_text())
    records = data.get("records", [])
    if not records:
        return []
    q_vec = hash_embedding(query)
    scored = [(cosine(q_vec, rec["embedding"]), rec) for rec in records]
    scored.sort(key=lambda pair: pair[0], reverse=True)
    out = []
    for score, rec in scored[:top_k]:
        if score < min_score:
            continue
        item = dict(rec)
        item["score"] = round(score, 4)
        item.pop("embedding", None)  # don't echo the raw vector into the report
        out.append(item)
    return out


def ollama_is_running(base_url: str = "http://localhost:11434", timeout: float = 2.0) -> bool:
    try:
        with urllib.request.urlopen(base_url.rstrip("/") + "/api/version", timeout=timeout) as resp:
            return resp.status == 200
    except Exception:
        return False


def call_chat_completions(base_url: str, api_key, model: str, prompt: str, timeout: int = 60) -> str:
    """Minimal OpenAI-compatible chat completion call using only the
    stdlib (urllib). Works against OpenRouter, OpenAI, and Ollama's
    OpenAI-compatible /v1 endpoint."""
    url = base_url.rstrip("/") + "/chat/completions"
    body = json.dumps(
        {
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.2,
        }
    ).encode("utf-8")
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"
    req = urllib.request.Request(url, data=body, headers=headers, method="POST")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        payload = json.loads(resp.read().decode("utf-8"))
    return payload["choices"][0]["message"]["content"]


def build_prompt(template: str, query: str, chunks) -> str:
    context = "\n\n".join(
        f"[{c['id']}] (score={c['score']}) {c['text']}" for c in chunks
    ) or "(no chunks retrieved)"
    return template.format(query=query, context=context)


def _mock_report(query: str, chunks, reason: str) -> str:
    return (
        "# Mock Research Report (DRY-RUN)\n\n"
        f"> {reason} This report was NOT generated by an LLM. It shows the\n"
        "> shape of what `synthesize()` would have produced with a real\n"
        "> hosted or local model attached.\n\n"
        f"**Query:** {query}\n\n"
        "## Executive Summary\n"
        f"(mock) Would summarize {len(chunks)} retrieved chunk(s) relevant to the query above.\n\n"
        "## Key Findings\n"
        + "".join(f"- (mock) Finding drawn from [{c['id']}], score={c['score']}\n" for c in chunks)
        + "\n## Sources\n"
        + "".join(f"- {c['id']} ({c['source_file']})\n" for c in chunks)
        + "\n## Disclaimer\n"
        "This report is synthesized from fixture documents for Chapter 1 Lab purposes.\n"
    )


def synthesize(query: str, cfg: dict, store_path, top_k_override: Optional[int] = None):
    """Retrieve top-N chunks for `query`, then synthesize a report.

    `top_k_override` (Chapter 3 Lab addition): lets --top-k on the CLI
    apply to the single-shot path too, so it's an apples-to-apples
    comparison against --mode expand-rerank's --top-k. Defaults to
    `None`, which preserves Chapter 1's original cfg-driven behavior.

    Returns (report_markdown, chunks_used, mode) where mode is one of
    "hosted-openrouter", "hosted-openai", "local-ollama", or "mock".
    """
    top_k = top_k_override if top_k_override is not None else cfg["researcher"].get("top_k", 5)
    min_score = cfg["researcher"].get("min_score", 0.0)
    chunks = retrieve(query, store_path, top_k=top_k, min_score=min_score)
    prompt = build_prompt(cfg["researcher"]["synthesis_prompt"], query, chunks)

    openrouter_key = os.environ.get("OPENROUTER_API_KEY")
    openai_key = os.environ.get("OPENAI_API_KEY")

    if openrouter_key:
        base_url = cfg["model"]["openrouter"]["base_url"]
        synthesis_model = cfg["model"]["synthesis"]
        model = synthesis_model.split("/", 1)[1] if synthesis_model.startswith("openrouter/") else synthesis_model
        print(f"[research] HOSTED path: OpenRouter base_url={base_url} model={model}")
        try:
            content = call_chat_completions(base_url, openrouter_key, model, prompt)
            return content, chunks, "hosted-openrouter"
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, KeyError, ValueError) as e:
            print(f"[research] hosted OpenRouter call failed ({e}); falling back")

    if openai_key:
        base_url = "https://api.openai.com/v1"
        model = "gpt-4o-mini"
        print(f"[research] HOSTED path: OpenAI base_url={base_url} model={model}")
        try:
            content = call_chat_completions(base_url, openai_key, model, prompt)
            return content, chunks, "hosted-openai"
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, KeyError, ValueError) as e:
            print(f"[research] hosted OpenAI call failed ({e}); falling back")

    ollama_base_v1 = cfg["model"]["ollama"]["base_url"]
    ollama_root = ollama_base_v1.rsplit("/v1", 1)[0]
    if ollama_is_running(ollama_root):
        synthesis_model = cfg["model"]["synthesis"]
        model = synthesis_model.split("/", 1)[1] if synthesis_model.startswith("ollama/") else "gemma4:26b"
        print(f"[research] LOCAL path: Ollama detected at {ollama_root}, model={model}")
        try:
            content = call_chat_completions(ollama_base_v1, None, model, prompt)
            return content, chunks, "local-ollama"
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, KeyError, ValueError) as e:
            print(f"[research] local Ollama call failed ({e}); falling back to mock mode")
    else:
        print(f"[research] no local Ollama detected at {ollama_root}")

    print("[research] MOCK/DRY-RUN mode: no OPENROUTER_API_KEY / OPENAI_API_KEY set in "
          "the environment, and no local Ollama server responded.")
    print("[research] This run WOULD have sent a /chat/completions request:")
    print(f"           model  : {cfg['model']['synthesis']}")
    print(f"           query  : {query}")
    print(f"           chunks : {len(chunks)} retrieved (top_k={top_k})")
    reason = "No OPENROUTER_API_KEY/OPENAI_API_KEY and no local Ollama were detected."
    return _mock_report(query, chunks, reason), chunks, "mock"


