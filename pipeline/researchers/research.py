# Chapter 3 Lab: retrieve_expand_rerank — the EXPAND_RERANK retrieval mode,
# scaled to this repo's pseudo-embedding and lexical-overlap rerank stand-in.
#
# PRODUCTION NOTE: freemarketresearcher.com's real researchers dispatch on a
# `mode` argument to RagSystem.researchers.base.BaseResearcher.retrieve():
# PLAIN (one search on the literal question), PILLARS (one search per fixed
# topic pillar), or EXPAND_RERANK (expand the question into variants, search
# each, dedupe by chunk text, then rerank on the *original* question) [src:
# ~/Projects/RagSystem/researchers/base.py:55-58, 258-272]. This function is
# that same EXPAND_RERANK shape, built from this module's own retrieve() plus
# pipeline.researchers.query_transform.expand_query and
# pipeline.researchers.rerank.rerank. It deliberately keeps Chapter 1's
# single-shot retrieve() untouched alongside it, so the Lab can run both
# modes against the same vector store and diff what each one returns.
#
# Why `search_top_k` is wider than the final `top_k`: the real system's
# per-variant search and its final rerank both use the same top_k_report
# (200) [src: ~/Projects/RagSystem/researchers/base.py:90-92], but with a
# corpus of thousands of chunks that's already a wide net per search; on
# this Lab's tiny fixture corpus (a handful of chunks), the only way to
# reproduce "a wider net before rerank narrows it back down" is to make the
# per-variant search explicitly wider than the single-shot comparison. That
# is a disclosed Lab-scale adjustment, not a different algorithm.
# ---------------------------------------------------------------------------

def retrieve_expand_rerank(
    query: str,
    store_path,
    top_k: int = 3,
    num_queries: int = 3,
    search_top_k: Optional[int] = None,
):
    """EXPAND_RERANK, Lab-scale: expand_query -> retrieve() per variant at
    `search_top_k` -> dedupe by chunk id -> rerank() on the original query,
    truncated to `top_k`.

    Returns (chunks, variants) so callers can show the reader the expanded
    queries, not just the final result.
    """
    if search_top_k is None:
        search_top_k = top_k + 2  # see module note above
    variants = expand_query(query, num_queries=num_queries)
    pool = {}
    for variant in variants:
        for chunk in retrieve(variant, store_path, top_k=search_top_k):
            pool.setdefault(chunk["id"], chunk)  # first search to find an id wins
    reranked = rerank(query, list(pool.values()), top_k=top_k)
    return reranked, variants


def main():
    ap = argparse.ArgumentParser(description="Ch1/Ch3 Lab researcher: retrieve + synthesize")
    ap.add_argument("--query", required=True)
    ap.add_argument("--collection", default="researcher_docs")
    ap.add_argument("--config", default=None)
    ap.add_argument("--output", default=None)
    ap.add_argument(
        "--mode",
        choices=["single-shot", "expand-rerank"],
        default="single-shot",
        help="single-shot = Ch1 Lab's one retrieve() call; "
        "expand-rerank = Ch3 Lab's expand -> multi-search -> dedupe -> rerank",
    )
    ap.add_argument("--top-k", type=int, default=None, help="overrides config researcher.top_k")
    ap.add_argument(
        "--store",
        default=None,
        help="Ch3 Lab: override the config-driven vector store path, matching "
        "pipeline.crawler.crawl's --store (keeps the Ch3 Lab's fixture corpus "
        "isolated from the shared data/vector_store.json)",
    )
    args = ap.parse_args()

    cfg = load_config(args.config)
    store_path = Path(args.store) if args.store else REPO_ROOT / cfg["vector_store"]["path"]

    if args.mode == "expand-rerank":
        top_k = args.top_k if args.top_k is not None else cfg["researcher"].get("top_k", 3)
        chunks, variants = retrieve_expand_rerank(args.query, store_path, top_k=top_k)
        print(f"[research] mode=expand-rerank query={args.query!r}")
        for i, v in enumerate(variants):
            print(f"[research]   variant {i}: {v}")
        print(f"[research]   retrieved {len(chunks)} chunk(s) after dedupe + rerank:")
        for c in chunks:
            print(f"[research]     {c['id']} rerank_score={c['rerank_score']} :: {c['text'][:90]}")
        prompt = build_prompt(cfg["researcher"]["synthesis_prompt"], args.query, chunks)
        print(f"[research]   (synthesis prompt built from these {len(chunks)} chunk(s); "
              "run with --mode single-shot on the same query to compare what Ch1's path retrieves)")
        out_dir = REPO_ROOT / cfg["publisher"]["output_dir"]
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = Path(args.output) if args.output else out_dir / "report_expand_rerank.md"
        out_path.write_text(prompt)
        print(f"[research] wrote retrieval+prompt trace to {out_path}")
        return

    report_md, chunks, mode = synthesize(args.query, cfg, store_path, top_k_override=args.top_k)

    print(f"[research] mode={mode} query={args.query!r}")
    print(f"[research]   retrieved {len(chunks)} chunk(s) (single-shot, no expansion, no rerank):")
    for c in chunks:
        print(f"[research]     {c['id']} score={c['score']} :: {c['text'][:90]}")

    out_dir = REPO_ROOT / cfg["publisher"]["output_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = Path(args.output) if args.output else out_dir / "report.md"
    out_path.write_text(report_md)
    print(f"[research] mode={mode} chunks_used={len(chunks)} -> wrote {out_path}")


if __name__ == "__main__":
    main()
