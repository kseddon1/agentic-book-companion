"""
tests/test_ch01_lab.py — Chapter 1 Lab verification.

Run with pytest if installed:
    pytest tests/test_ch01_lab.py -v

Or directly with plain Python (no pytest required -- this is the path
the Chapter 1 Lab actually documents, since a from-scratch reader may
not have pytest installed):
    python3 tests/test_ch01_lab.py

Asserts: the vector store has N > 0 chunks after crawl, a report was
generated by research, and the dry-run publish + snapshot output files
all exist after pipeline/run_pipeline.py runs end to end.
"""
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def test_pipeline_runs_end_to_end():
    result = subprocess.run(
        [
            sys.executable,
            str(REPO_ROOT / "pipeline" / "run_pipeline.py"),
            "--query",
            "What are the basics of serving an LLM locally?",
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert result.returncode == 0, f"run_pipeline.py failed:\n{result.stdout}\n{result.stderr}"

    store_path = REPO_ROOT / "data" / "vector_store.json"
    assert store_path.exists(), "vector store was not created"
    data = json.loads(store_path.read_text())
    assert len(data.get("records", [])) > 0, "vector store has 0 chunks"

    out_dir = REPO_ROOT / "output"
    assert (out_dir / "report.md").exists(), "research stage did not write report.md"
    assert (out_dir / "post.md").exists(), "publish stage did not write post.md"
    assert (out_dir / "market_state.json").exists(), "snapshot stage did not write market_state.json"

    snapshot = json.loads((out_dir / "market_state.json").read_text())
    # Field renamed from "as_of" to "updated_at" during the Chapter 10
    # Technical Core pass, to match the real production field name
    # (market_state_publisher.py / functions.php) -- see
    # pipeline/snapshot/market_state.py's "CHAPTER 10 FIX" docstring note.
    assert "regime" in snapshot and "updated_at" in snapshot


if __name__ == "__main__":
    test_pipeline_runs_end_to_end()
    print("OK: Chapter 1 Lab pipeline ran end to end and produced all expected artifacts.")
